package git

import (
	"strconv"
	"strings"
)

// diffNoNewlineMarker is git's exact, locale-stable (we force LC_ALL=C)
// end-of-hunk marker; a body line only reaches it when it matches whole.
const diffNoNewlineMarker = `\ No newline at end of file`

// DiffLineType classifies one line inside a hunk: unchanged context, an
// addition on the new side, or a deletion on the old side.
type DiffLineType string

const (
	DiffLineContext DiffLineType = "context"
	DiffLineAdd     DiffLineType = "add"
	DiffLineDel     DiffLineType = "del"
)

// DiffLine is one hunk line. OldNum/NewNum are 1-based line numbers in the
// old and new file; 0 means the line does not exist on that side. Text
// excludes the leading +/-/space marker.
type DiffLine struct {
	Type      DiffLineType `json:"type"`
	OldNum    int          `json:"oldNum"`
	NewNum    int          `json:"newNum"`
	Text      string       `json:"text"`
	NoNewline bool         `json:"noNewline,omitempty"`
}

// DiffHunk is one @@-delimited block. Header keeps the raw "@@ ... @@"
// line, including any trailing section heading git prints after it.
type DiffHunk struct {
	Header   string     `json:"header"`
	OldStart int        `json:"oldStart"`
	OldCount int        `json:"oldCount"`
	NewStart int        `json:"newStart"`
	NewCount int        `json:"newCount"`
	Lines    []DiffLine `json:"lines"`
}

// FileDiff is the parsed unified diff of a single file.
type FileDiff struct {
	OldPath string     `json:"oldPath"`
	NewPath string     `json:"newPath"`
	Hunks   []DiffHunk `json:"hunks"`
}

// parseUnifiedDiff parses `git diff`-style patch output (issue #24). The
// parser only ever sees output generated by this package's own git
// invocations, whose headers are pinned by machine flags (see buildGitCmd),
// so anything before the first hunk that is not a recognized header line is
// ignored for forward compatibility, while a truncated or over-full hunk is
// a hard parse_failed error.
func parseUnifiedDiff(data []byte) ([]FileDiff, error) {
	p := &diffParser{cur: -1}
	lines := strings.Split(string(data), "\n")
	for _, line := range lines {
		if err := p.feed(line); err != nil {
			return nil, err
		}
	}
	if p.inHunk && (p.oldRem > 0 || p.newRem > 0) {
		return nil, diffParseError("hunk truncated at end of output: " + p.hunk().Header)
	}
	return p.files, nil
}

type diffParser struct {
	files  []FileDiff
	cur    int // index into files of the current section; -1 before the first
	inHunk bool
	// current hunk bookkeeping: remaining lines per side and the next
	// 1-based number on each side
	oldRem, newRem int
	oldNum, newNum int
}

func (p *diffParser) feed(line string) error {
	if p.inHunk {
		// a context line or the EOF marker can arrive after both counts are
		// spent (the marker always trails the last body line), so the hunk
		// closes lazily; any other line ends it
		if line == diffNoNewlineMarker || strings.HasPrefix(line, " ") || p.oldRem > 0 || p.newRem > 0 {
			return p.feedHunk(line)
		}
		p.inHunk = false
	}
	switch {
	case line == "":
		// blank separator between sections, or the final newline
	case strings.HasPrefix(line, "diff --git "):
		p.files = append(p.files, FileDiff{Hunks: []DiffHunk{}})
		p.cur = len(p.files) - 1
	case strings.HasPrefix(line, "--- "), strings.HasPrefix(line, "+++ "):
		if p.cur < 0 {
			return diffParseError("file header outside any section: " + line)
		}
		dst, side := &p.file().OldPath, "a/"
		if line[0] == '+' {
			dst, side = &p.file().NewPath, "b/"
		}
		return p.setPath(dst, line[4:], side)
	case strings.HasPrefix(line, "@@ "):
		return p.startHunk(line)
		// unrecognized header lines (index, mode, ...) fall through
	}
	return nil
}

func (p *diffParser) feedHunk(line string) error {
	if line == "" {
		return diffParseError("empty line inside hunk")
	}
	h := p.hunk()
	switch line[0] {
	case ' ':
		if p.oldRem == 0 || p.newRem == 0 {
			return diffParseError("context line beyond declared range: " + line)
		}
		p.oldRem--
		p.newRem--
		h.Lines = append(h.Lines, DiffLine{Type: DiffLineContext, OldNum: p.oldNum, NewNum: p.newNum, Text: line[1:]})
		p.oldNum++
		p.newNum++
	case '-':
		if p.oldRem == 0 {
			return diffParseError("removed line beyond declared range: " + line)
		}
		p.oldRem--
		h.Lines = append(h.Lines, DiffLine{Type: DiffLineDel, OldNum: p.oldNum, Text: line[1:]})
		p.oldNum++
	case '+':
		if p.newRem == 0 {
			return diffParseError("added line beyond declared range: " + line)
		}
		p.newRem--
		h.Lines = append(h.Lines, DiffLine{Type: DiffLineAdd, NewNum: p.newNum, Text: line[1:]})
		p.newNum++
	case '\\':
		if line != diffNoNewlineMarker {
			return diffParseError("unexpected line inside hunk: " + line)
		}
		n := len(h.Lines)
		if n == 0 {
			return diffParseError(`no-newline marker without a preceding line`)
		}
		h.Lines[n-1].NoNewline = true
	default:
		return diffParseError("unexpected line inside hunk: " + line)
	}
	return nil
}

func (p *diffParser) file() *FileDiff {
	return &p.files[p.cur]
}

func (p *diffParser) hunk() *DiffHunk {
	f := p.file()
	return &f.Hunks[len(f.Hunks)-1]
}

func (p *diffParser) startHunk(line string) error {
	if p.cur < 0 {
		return diffParseError("hunk outside any file section: " + line)
	}
	oldStart, oldCount, newStart, newCount, err := parseRangeHeaders(line)
	if err != nil {
		return err
	}
	p.file().Hunks = append(p.file().Hunks, DiffHunk{
		Header:   line,
		OldStart: oldStart,
		OldCount: oldCount,
		NewStart: newStart,
		NewCount: newCount,
		Lines:    []DiffLine{},
	})
	p.inHunk = true
	p.oldRem, p.newRem = oldCount, newCount
	p.oldNum, p.newNum = oldStart, newStart
	return nil
}

// parseRangeHeaders decodes "@@ -old[,count] +new[,count] @@ [heading]",
// where an omitted count means exactly one line (git's default -U3 output
// for a one-line file is "@@ -1 +1 @@").
func parseRangeHeaders(line string) (oldStart, oldCount, newStart, newCount int, err error) {
	rest, ok := strings.CutPrefix(line, "@@ -")
	if !ok {
		return 0, 0, 0, 0, diffParseError("malformed hunk header: " + line)
	}
	oldText, rest, ok := strings.Cut(rest, " +")
	if !ok {
		return 0, 0, 0, 0, diffParseError("malformed hunk header: " + line)
	}
	newText, rest, ok := strings.Cut(rest, " @@")
	if !ok || (rest != "" && !strings.HasPrefix(rest, " ")) {
		return 0, 0, 0, 0, diffParseError("malformed hunk header: " + line)
	}
	if oldStart, oldCount, err = parseRange(oldText, line); err != nil {
		return
	}
	if newStart, newCount, err = parseRange(newText, line); err != nil {
		return
	}
	return oldStart, oldCount, newStart, newCount, nil
}

func parseRange(text, header string) (start, count int, err error) {
	startText, countText, hasCount := strings.Cut(text, ",")
	start, err = strconv.Atoi(startText)
	if err != nil || start < 0 {
		return 0, 0, diffParseError("malformed hunk header: " + header)
	}
	count = 1
	if hasCount {
		count, err = strconv.Atoi(countText)
		if err != nil || count < 0 {
			return 0, 0, diffParseError("malformed hunk header: " + header)
		}
	}
	return start, count, nil
}

// setPath decodes one endpoint of the file pair from a ---/+++ header. The
// path may be followed by a TAB and timestamp; quoted form `"a/..."` is
// used whenever the name contains characters git considers unusual.
func (p *diffParser) setPath(dst *string, token, side string) error {
	name, _, _ := strings.Cut(token, "\t")
	path, err := unquoteGitPath(name)
	if err != nil {
		return err
	}
	*dst = strings.TrimPrefix(path, side)
	return nil
}

// unquoteGitPath decodes git's C-style path quoting (core.quotePath): a
// quoted name starts and ends with a double quote and escapes non-printable
// and non-ASCII bytes as \NNN octal sequences plus the usual single-letter
// escapes. Unquoted names pass through unchanged.
func unquoteGitPath(s string) (string, error) {
	if !strings.HasPrefix(s, "\"") {
		return s, nil
	}
	if len(s) < 2 || !strings.HasSuffix(s, "\"") {
		return "", diffParseError("malformed quoted path: " + s)
	}
	body := s[1 : len(s)-1]
	var b strings.Builder
	for i := 0; i < len(body); i++ {
		c := body[i]
		if c != '\\' {
			b.WriteByte(c)
			continue
		}
		i++
		if i >= len(body) {
			return "", diffParseError("dangling escape in quoted path: " + s)
		}
		switch e := body[i]; e {
		case '"', '\\':
			b.WriteByte(e)
		case 'a':
			b.WriteByte('\a')
		case 'b':
			b.WriteByte('\b')
		case 'f':
			b.WriteByte('\f')
		case 'n':
			b.WriteByte('\n')
		case 'r':
			b.WriteByte('\r')
		case 't':
			b.WriteByte('\t')
		case 'v':
			b.WriteByte('\v')
		default:
			if e < '0' || e > '7' {
				return "", diffParseError("unknown escape \\" + string(e) + " in quoted path: " + s)
			}
			val := int(e - '0')
			for d := 0; d < 2 && i+1 < len(body) && body[i+1] >= '0' && body[i+1] <= '7'; d++ {
				i++
				val = val*8 + int(body[i]-'0')
			}
			b.WriteByte(byte(val))
		}
	}
	return b.String(), nil
}

func diffParseError(msg string) error {
	return &GitError{Code: CodeParseFailed, Message: msg, ExitCode: -1}
}
